# analyze.py: measure the song and write src/songmap.js (beats, downbeats, hits, energy, timed words).
#   uv run --python 3.12 --with librosa --with soundfile tools/analyze.py
import json
import sys
from pathlib import Path

import librosa
import numpy as np

ROOT = Path(__file__).resolve().parent.parent
AUDIO = ROOT / "assets" / "operation-walkies.mp3"
WHISPER = ROOT / "assets" / "whisper.json"
OUT = ROOT / "src" / "songmap.js"

y, sr = librosa.load(AUDIO, sr=22050, mono=True)
dur = len(y) / sr
hop = 256
oenv = librosa.onset.onset_strength(y=y, sr=sr, hop_length=hop)
# The song sits at about 90.6 BPM (a 181 BPM punk pulse on the eighths); the default tracker locks onto a false 120.
tempo, beat_f = librosa.beat.beat_track(onset_envelope=oenv, sr=sr, hop_length=hop, units="frames", start_bpm=90.6, tightness=400)
tempo = float(np.atleast_1d(tempo)[0])
beats = librosa.frames_to_time(beat_f, sr=sr, hop_length=hop)

# Downbeat phase: the beat phase (mod 4) with the most low-band onset energy.
S = np.abs(librosa.stft(y, n_fft=2048, hop_length=hop))
freqs = librosa.fft_frequencies(sr=sr, n_fft=2048)
low = S[freqs < 150].sum(axis=0)
low_on = np.maximum(0, np.diff(low, prepend=low[0]))
bl = np.array([low_on[max(0, f - 3):f + 4].max() for f in beat_f])
mid = S[(freqs > 1500) & (freqs < 6000)].sum(axis=0)
mid_on = np.maximum(0, np.diff(mid, prepend=mid[0]))
ml = np.array([mid_on[max(0, f - 3):f + 4].max() for f in beat_f])
loud = (beats > 24) & (beats < 100)
idx = np.arange(len(beats))
phase_score = [float(bl[loud & (idx % 4 == p)].mean()) for p in range(4)]
snare_score = [float(ml[loud & (idx % 4 == p)].mean()) for p in range(4)]
phase = int(np.argmax(phase_score))
print("snare scores by phase:", np.round(snare_score, 2))
rms_f = librosa.feature.rms(y=y, frame_length=1024, hop_length=hop)[0]
t_f = librosa.frames_to_time(np.arange(len(rms_f)), sr=sr, hop_length=hop)
for a, b in [(14, 25), (100, 106), (122, 135), (144, 156), (175, 191), (198, 204.7)]:
    seg_t = np.arange(a, b, 0.25)
    print(f"rms {a}-{b}:", " ".join(f"{np.interp(q, t_f, rms_f) / rms_f.max() * 99:.0f}" for q in seg_t))

# Energy envelope at 10 Hz, normalised 0..1.
rms = librosa.feature.rms(y=y, frame_length=4096, hop_length=hop)[0]
t_rms = librosa.frames_to_time(np.arange(len(rms)), sr=sr, hop_length=hop)
grid = np.arange(0, dur, 0.1)
energy = np.interp(grid, t_rms, rms)
energy = energy / energy.max()

# Strong hits: the biggest onset peaks (for impact frames).
on_f = librosa.onset.onset_detect(onset_envelope=oenv, sr=sr, hop_length=hop, backtrack=False, units="frames")
on_t = librosa.frames_to_time(on_f, sr=sr, hop_length=hop)
on_s = oenv[on_f] / oenv.max()
hits = [[round(float(t), 3), round(float(s), 3)] for t, s in zip(on_t, on_s) if s > 0.45]

ibi = np.diff(beats)
print(f"duration {dur:.2f}s  tempo {tempo:.2f} bpm  beats {len(beats)}  median beat {np.median(ibi):.4f}s ({60 / np.median(ibi):.2f} bpm)")
print("first beats:", np.round(beats[:10], 3))
print("downbeat phase scores:", np.round(phase_score, 2), "→ phase", phase)
print("beat interval spread:", round(float(ibi.std()), 4))

# Energy per 2 s, as a quick text picture of the song's shape.
for a in range(0, int(dur), 2):
    e = energy[int(a * 10):int((a + 2) * 10)].mean()
    print(f"{a:4d}s {'#' * int(e * 60)}")

wh = json.loads(WHISPER.read_text())
song = {
    "dur": round(dur, 3),
    "bpm": round(60 / float(np.median(ibi)), 3),
    "beats": [round(float(b), 3) for b in beats],
    "phase": phase,
    "energy": [round(float(e), 3) for e in energy],
    "hits": hits,
    "words": [[w["w"], w["s"], w["e"]] for w in wh["words"]],
    "segs": [[s["start"], s["end"], s["text"].strip()] for s in wh["segments"]],
}
OUT.parent.mkdir(parents=True, exist_ok=True)
OUT.write_text("// Generated by tools/analyze.py from the song audio and whisper.json. Do not edit by hand.\nconst SONG = " + json.dumps(song, separators=(",", ":")) + ";\n")
print("wrote", OUT)
